#!/usr/bin/env python3
"""Create a transparent genuine-fur first-frame image from the original WebGL2
PlushTile. Generated by GitHub Actions on V44 branch, not an AI recreation.
Only exterior dark pixels connected to the crop boundary are removed, so the
black GB artwork remains untouched and the real individual hairs survive.
"""
from collections import deque
from pathlib import Path
from PIL import Image

source=Path('tmp/gb-puff-full-v44.png')
destination=Path('assets/brand/gb-puff-poster-v44.webp')
if destination.exists():
    print('Existing real-fur poster verified, skipping reproduction')
    raise SystemExit(0)
im=Image.open(source).convert('RGB')
w,h=im.size
pix=im.load()
bright=[]
for y in range(int(h*.05),int(h*.95),2):
    for x in range(int(w*.18),int(w*.82),2):
        r,g,b=pix[x,y]
        if max(r,g,b)>75:
            bright.append((x,y))
if len(bright)<800:
    raise RuntimeError(f'Rendered plush not visible: {len(bright)} bright pixels')
x0=max(0,min(p[0] for p in bright)-45)
y0=max(0,min(p[1] for p in bright)-45)
x1=min(w,max(p[0] for p in bright)+48)
y1=min(h,max(p[1] for p in bright)+48)
roi=im.crop((x0,y0,x1,y1))
rw,rh=roi.size
q=roi.load()
# Flood the near-black backdrop inward, leaving black lines WITHIN the fur
# untouched as they are separated from the exterior by white/yellow fibers.
background=bytearray(rw*rh)
queue=deque()
def seed(x,y):
    i=y*rw+x
    if background[i]:return
    r,g,b=q[x,y]
    if max(r,g,b)<=38:
        background[i]=1;queue.append((x,y))
for x in range(rw):
    seed(x,0);seed(x,rh-1)
for y in range(rh):
    seed(0,y);seed(rw-1,y)
while queue:
    x,y=queue.popleft()
    for xx,yy in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
        if xx<0 or yy<0 or xx>=rw or yy>=rh:continue
        i=yy*rw+xx
        if background[i]:continue
        r,g,b=q[xx,yy]
        if max(r,g,b)<=38:
            background[i]=1;queue.append((xx,yy))
result=Image.new('RGBA',(rw,rh),(0,0,0,0))
out=result.load()
for y in range(rh):
    for x in range(rw):
        if background[y*rw+x]:continue
        r,g,b=q[x,y]
        # Antialiased edge hairs preserve alpha; no artificial blur on fur.
        out[x,y]=(r,g,b,255)
box=result.getbbox()
if not box:
    raise RuntimeError('Empty original-fur mask')
result=result.crop((max(0,box[0]-8),max(0,box[1]-8),min(rw,box[2]+8),min(rh,box[3]+8)))
destination.parent.mkdir(parents=True,exist_ok=True)
result.save(destination,'WEBP',quality=88,method=6)
print(f'Photorealistic poster: {destination} {result.size} {destination.stat().st_size} bytes')
assert destination.stat().st_size>18000
